"""Generates the recompiler's differential tests (one C function per instruction).

Takes the P1 instructions from the analysis listing (Phase 1), picks up to N real instances of
each distinct opcode (distinct extension words) and emits, for each one, the generator's C wrapped
in a function. The harness (differential.c) runs each instruction in Musashi and in the generated
C from random states and compares the results.

The output contains code derived from the game: it is written to the build directory and is
never committed.

Usage: python generate_tests.py --roms DIR --listing FILE --output FILE.c [--per-opcode N] [--cycles BIN]
"""
from __future__ import annotations

import argparse
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "tools" / "recomp68k"))
from decoder import decode                        # noqa: E402
import generator                                  # noqa: E402
from generator import Emitter, Unsupported        # noqa: E402

HEADER = r"""/* GENERATED by tests/differential/generate_tests.py: DO NOT EDIT, DO NOT COMMIT. */
#include <string.h>
#include "cpu68k.h"
#define CIC(n) (n)
#include "cycles68k.h"
#include "tests.h"

#define PD_NEXT(d)             do { c->pc = (d); return; } while (0)
#define PD_JUMP(d)             do { c->pc = (d); return; } while (0)
#define PD_JUMP_DYN(e)         do { c->pc = (e); return; } while (0)
#define PD_CALL(d, r)          PD_JUMP(d)
#define PD_CALL_DYN(e, r)      PD_JUMP_DYN(e)
#define PD_RETURN(e)           PD_JUMP_DYN(e)
#define PD_EXCEPTION(v, pc)    do { cpu_exception(c, (v), (pc)); return; } while (0)
#define PD_SR_CHANGED(d)       PD_NEXT(d)
#define PD_STOP(d)             PD_NEXT(d)
#define PD_EXTERNAL_RESET()    ((void)0)
#define PD_BEGIN(o)            do { c->op = (o); c->start_cycle = c->cycles; } while (0)

"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--roms", type=Path, required=True)
    ap.add_argument("--listing", type=Path, required=True)
    ap.add_argument("--output", type=Path, required=True)
    ap.add_argument("--per-opcode", type=int, default=2)
    ap.add_argument("--cycles", type=Path, help="base cycle table (dump_cycles)")
    a = ap.parse_args()
    if a.cycles:
        generator.load_cycles(a.cycles)

    raw = (a.roms / "mslugx_game_m68k").read_bytes()[:1 << 20]
    cpu = bytearray(len(raw))
    cpu[0::2], cpu[1::2] = raw[1::2], raw[0::2]
    read16 = lambda d: int.from_bytes(cpu[d:d + 2], "big") if d + 2 <= len(cpu) else 0  # noqa: E731

    chosen: dict[int, list] = defaultdict(list)
    seen_ext: set[bytes] = set()
    for line in a.listing.read_text(encoding="utf-8").splitlines():
        m = re.match(r"^([0-9A-F]{6})", line)
        if not m:
            continue
        d = int(m.group(1), 16)
        i = decode(read16, d)
        if i is None:
            continue
        raw_bytes = bytes(cpu[d:d + i.length])
        if len(chosen[i.opcode]) >= a.per_opcode or raw_bytes in seen_ext:
            continue
        seen_ext.add(raw_bytes)
        chosen[i.opcode].append(i)

    functions, table, unsupported = [], [], Counter()
    for opcode in sorted(chosen):
        for i in chosen[opcode]:
            try:
                body = Emitter(i).emit()
            except Unsupported as e:
                unsupported[str(e)] += 1
                continue
            name = f"i_{i.addr:06X}"
            functions.append(f"static void {name}(Cpu68k *c)\n{{\n    " + "\n    ".join(body) + "\n}\n")
            table.append(f'    {{0x{i.addr:06X}u, {name}, "{i.text()}"}},')

    a.output.parent.mkdir(parents=True, exist_ok=True)
    a.output.write_text(HEADER + "\n".join(functions) +
                        "\nconst Test tests[] = {\n" + "\n".join(table) + "\n};\n" +
                        f"const int n_tests = {len(table)};\n", encoding="utf-8")
    print(f"tests generated: {len(table)} (distinct opcodes: {len(chosen)})")
    for k, n in unsupported.most_common():
        print(f"  UNSUPPORTED: {k} x{n}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
