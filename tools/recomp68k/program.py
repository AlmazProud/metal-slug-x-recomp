"""Generates the complete recompiled program (the user's P1 and BIOS) as C functions.

Function entries:
  - function starts from the analysis (Phase 1 listings),
  - observed targets of indirect jumps (MAME dynamic coverage),
  - return addresses of every JSR/BSR (continuations: they allow resuming in native code
    when a call does not return "cleanly").

Each function is emitted with one label per instruction. Jumps to instructions in the same
function are `goto`s; backward jumps first go through a checkpoint (cycle limit -> dispatcher)
so that wait loops do not block interrupts. Everything else returns to the dispatcher with
c->pc.

The output is derived from the game program: it is written to the build directory and is
never committed.

Usage: python program.py --roms DIR --listings L1 [L2...] --coverage J [J...] --cycles BIN
                         --output DIR [--files N] [--no-per-instruction-points]
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import generator                                  # noqa: E402
from decoder import decode                        # noqa: E402
from generator import Emitter, Unsupported        # noqa: E402

HEADER = r"""/* GENERATED by tools/recomp68k/program.py: DO NOT EDIT, DO NOT COMMIT. */
#include <string.h>
#include "cpu68k.h"
#include "cycles68k.h"
#include "dispatcher.h"

#define PD_JUMP_DYN(e)         do { c->pc = (e) & 0xFFFFFFu; return; } while (0)
#define PD_RETURN(e)           PD_JUMP_DYN(e)
#define PD_EXCEPTION(v, pc)    do { cpu_exception(c, (v), (pc)); return; } while (0)
#define PD_SR_CHANGED(d)       do { c->pc = (d); return; } while (0)
#define PD_STOP(d)             do { c->pc = (d); c->stopped = 1; return; } while (0)
#define PD_EXTERNAL_RESET()    ((void)0)
/* Opcode and instruction start, for interrupt sampling (cycles68k.h). */
#define PD_BEGIN(o)            do { c->op = (o); c->start_cycle = c->cycles; } while (0)
"""

RE_JUMP = re.compile(r"PD_(NEXT|JUMP)\(0x([0-9A-F]+)u\);")
RE_CALL = re.compile(r"PD_CALL\(0x([0-9A-F]+)u, 0x([0-9A-F]+)u\);")
RE_CALL_DYN = re.compile(r"PD_CALL_DYN\((\w+), 0x([0-9A-F]+)u\);")


class Memory:
    def __init__(self, roms: Path):
        def cpu(b):
            a = bytearray(b)
            a[0::2], a[1::2] = b[1::2], b[0::2]
            return bytes(a)
        p1 = (roms / "mslugx_game_m68k").read_bytes()[:1 << 20]
        bios = (roms / "mslugx_bios_m68k").read_bytes()
        # SHA-256 of the files the program is generated from: the port only uses the recompiled
        # program with a copy whose P1 and BIOS have these hashes (otherwise, the interpreter).
        self.p1_sha256 = hashlib.sha256(p1).hexdigest()
        self.bios_sha256 = hashlib.sha256(bios).hexdigest()
        self.p1 = cpu(p1)
        self.bios = cpu(bios)

    def read16(self, d: int) -> int:
        if d + 2 <= len(self.p1):
            return int.from_bytes(self.p1[d:d + 2], "big")
        if 0xC00000 <= d and d - 0xC00000 + 2 <= len(self.bios):
            o = d - 0xC00000
            return int.from_bytes(self.bios[o:o + 2], "big")
        return 0


def read_listings(paths):
    instr, entries = set(), set()
    for path in paths:
        for line in Path(path).read_text(encoding="utf-8").splitlines():
            m = re.match(r"^; ---- funcion ([0-9A-F]{6})", line)
            if m:
                entries.add(int(m.group(1), 16))
                continue
            m = re.match(r"^([0-9A-F]{6})", line)
            if m:
                instr.add(int(m.group(1), 16))
    return instr, entries


def successors(i) -> list[int]:
    """Intraprocedural successors (calls continue at the next instruction)."""
    nxt = i.addr + i.length
    if i.op in ("rts", "rte", "rtr", "jmp", "illegal", "trap", "stop"):
        return []
    if i.op == "bra":
        return [i.target]
    if i.op in ("bcc", "dbcc"):
        return [i.target, nxt]
    if i.op in ("move_to_sr", "andi_sr", "ori_sr", "eori_sr"):
        return []                       # they return to the dispatcher (may enable IRQs)
    return [nxt]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--roms", type=Path, required=True)
    ap.add_argument("--listings", type=Path, nargs="+", required=True)
    ap.add_argument("--coverage", type=Path, nargs="*", default=[])
    ap.add_argument("--cycles", type=Path, required=True)
    ap.add_argument("--output", type=Path, required=True)
    ap.add_argument("--files", type=int, default=16, help="fixed number of output .c files")
    ap.add_argument("--no-per-instruction-points", action="store_true",
                    help="checkpoints only on backward jumps (interrupts are taken at the "
                         "dispatch points, not at the exact instruction boundary)")
    a = ap.parse_args()
    per_instruction = not a.no_per_instruction_points
    generator.load_cycles(a.cycles)
    mem = Memory(a.roms)

    instr, entries = read_listings(a.listings)
    for path in a.coverage:
        if path.exists():
            for _src, dst, _bank in json.loads(path.read_text())["indirectos"]:
                if dst in instr:
                    entries.add(dst)

    decoded = {}
    for d in sorted(instr):
        i = decode(mem.read16, d)
        if i is not None:
            decoded[d] = i
    # Regions: connected components of the intraprocedural control-flow graph. Each instruction
    # is emitted ONCE, inside the region that contains it; the region is entered through a switch
    # on c->pc, so any recompiled instruction is a valid entry point (the interpreter is not
    # needed when returning from a checkpoint in the middle of a loop).
    parent = {d: d for d in decoded}

    def root(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    for d, i in decoded.items():
        for s in successors(i):
            if s in decoded:
                ra, rb = root(d), root(s)
                if ra != rb:
                    parent[max(ra, rb)] = min(ra, rb)
    regions: dict[int, list[int]] = {}
    for d in sorted(decoded):
        regions.setdefault(root(d), []).append(d)

    a.output.mkdir(parents=True, exist_ok=True)
    for old in a.output.glob("program_*.c"):
        old.unlink()

    functions, registrations, unsupported = [], [], 0
    for r, members in sorted(regions.items()):
        in_region = set(members)
        name = f"r_{r:06X}"
        cases = " ".join(f"case 0x{d:X}u: goto L_{d:06X};" for d in members)
        lines = [f"static void {name}(Cpu68k *c)", "{",
                 f"    switch (c->pc) {{ {cases} default: rc_interpreter_step(c); return; }}"]
        for d in members:
            i = decoded[d]
            try:
                body = Emitter(i).emit()
            except Unsupported:
                unsupported += 1
                body = [f"rc_interpreter_step(c); return; /* unsupported */"]
            text = "\n        ".join(body)

            def jump(m, d=d):
                target = int(m.group(2), 16)
                if target in in_region:
                    if target <= d and not per_instruction:   # backward: checkpoint
                        return (f"if (c->cycles >= rc_cycle_limit) {{ c->pc = 0x{target:X}u; return; }} "
                                f"goto L_{target:06X};")
                    return f"goto L_{target:06X};"
                return f"{{ c->pc = 0x{target:X}u; return; }}"

            def resume(ret):
                if ret in in_region:
                    return f"goto L_{ret:06X};"
                return f"{{ c->pc = 0x{ret:X}u; return; }}"

            text = RE_JUMP.sub(jump, text)
            text = RE_CALL.sub(lambda m: f"if (!rc_call(c, 0x{m.group(1)}u, 0x{m.group(2)}u)) return; "
                                         + resume(int(m.group(2), 16)), text)
            text = RE_CALL_DYN.sub(lambda m: f"if (!rc_call(c, {m.group(1)}, 0x{m.group(2)}u)) return; "
                                             + resume(int(m.group(2), 16)), text)
            lines.append(f"  L_{d:06X}: {{  /* {i.text()} */")
            if per_instruction:
                # Checkpoint at every instruction boundary: events (interrupts, video lines) are
                # serviced before the first instruction that starts at or after their cycle, as
                # on the real 68000.
                lines.append(f"        if (c->cycles >= rc_cycle_limit) {{ c->pc = 0x{d:X}u; return; }}")
            lines.append("        " + text)
            lines.append("    }")
        lines.append("}")
        functions.append("\n".join(lines))
        registrations.append((name, members))

    n_files = 0
    per_file = max(1, -(-len(functions) // a.files))
    for k in range(0, a.files * per_file, per_file):
        chunk = functions[k:k + per_file]
        register_body = "\n".join(f"    for (size_t i = 0; i < sizeof d_{n} / sizeof d_{n}[0]; i++) rc_register(d_{n}[i], {n});"
                                  for n, _ in registrations[k:k + per_file])
        tables = "\n".join(f"static const uint32_t d_{n}[] = {{{', '.join(f'0x{d:X}u' for d in ms)}}};"
                           for n, ms in registrations[k:k + per_file])
        (a.output / f"program_{n_files:03d}.c").write_text(
            HEADER + "\n\n".join(chunk) + "\n\n" + tables +
            f"\n\nvoid program_register_{n_files:03d}(void)\n{{\n{register_body}\n}}\n", encoding="utf-8")
        n_files += 1
    calls = "\n".join(f"    program_register_{n:03d}();" for n in range(n_files))
    decls = "\n".join(f"void program_register_{n:03d}(void);" for n in range(n_files))
    (a.output / "program_registry.c").write_text(
        "/* GENERATED: DO NOT EDIT, DO NOT COMMIT. */\n" + decls +
        f"\n\nconst char program_p1_sha256[] = \"{mem.p1_sha256}\";\n"
        f"const char program_bios_sha256[] = \"{mem.bios_sha256}\";\n"
        f"\nvoid program_register(void)\n{{\n{calls}\n}}\n", encoding="utf-8")
    print(f"regions: {len(functions)}  instructions: {len(decoded)}  files: {n_files}  "
          f"unsupported: {unsupported}  (analysis entries: {len(entries)})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
