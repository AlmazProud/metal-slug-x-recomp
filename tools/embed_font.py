"""Turns a font file (TTF, OFL licensed) into a C source with its bytes, for the menu (ui_font.c).

The repo only holds text (tools/check_commit.py), so the fonts go in as C arrays generated by
this script; the TTF files themselves stay outside the repo. Usage:

    python tools/embed_font.py <font.ttf> <symbol> <output.c>

The source records the font file's SHA256 so it can be checked against the original.
"""
from __future__ import annotations

import hashlib
import sys
from pathlib import Path


def main() -> int:
    if len(sys.argv) != 4:
        print(__doc__)
        return 2
    font, symbol, out = Path(sys.argv[1]), sys.argv[2], Path(sys.argv[3])
    data = font.read_bytes()
    lines = [",".join(str(b) for b in data[i:i + 40]) + "," for i in range(0, len(data), 40)]
    out.write_text(
        f"/* {font.name} ({len(data)} bytes, SHA256 {hashlib.sha256(data).hexdigest()}),\n"
        f" * SIL Open Font License 1.1 (see the OFL-*.txt file next to it).\n"
        f" * Generated by tools/embed_font.py: do not edit. */\n"
        f"#include <stddef.h>\n\n"
        f"const unsigned char {symbol}[] = {{\n" + "\n".join(lines) + "\n};\n"
        f"const size_t {symbol}_size = sizeof {symbol};\n",
        encoding="ascii", newline="\n")
    print(f"{out}: {len(data)} bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
