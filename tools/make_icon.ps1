# make_icon.ps1 -Png IMAGE.png -Ico OUT.ico [-Rc OUT.rc]
# Builds a Windows icon (16 to 256 pixels, each size a PNG inside the .ico) from the user's own
# image, for personal builds only (src/CMakeLists.txt, PD_ICON_DIR): the image and the icon stay
# outside the repository and out of the distributable build. With -Rc it also writes the resource
# script that puts the icon in the executable (id 1, which the window uses too).
param([Parameter(Mandatory)] [string]$Png, [Parameter(Mandatory)] [string]$Ico, [string]$Rc = "")
$ErrorActionPreference = "Stop"
Add-Type -AssemblyName System.Drawing
$src = [Drawing.Image]::FromFile((Resolve-Path $Png))
$frames = @()
foreach ($size in 16, 24, 32, 48, 64, 128, 256) {
    $bmp = New-Object Drawing.Bitmap $size, $size, ([Drawing.Imaging.PixelFormat]::Format32bppArgb)
    $g = [Drawing.Graphics]::FromImage($bmp)
    $g.InterpolationMode = [Drawing.Drawing2D.InterpolationMode]::HighQualityBicubic
    $g.SmoothingMode = [Drawing.Drawing2D.SmoothingMode]::HighQuality
    $g.PixelOffsetMode = [Drawing.Drawing2D.PixelOffsetMode]::HighQuality
    $g.DrawImage($src, 0, 0, $size, $size)
    $g.Dispose()
    $ms = New-Object IO.MemoryStream
    $bmp.Save($ms, [Drawing.Imaging.ImageFormat]::Png)
    $bmp.Dispose()
    $frames += , @($size, $ms.ToArray())
}
$src.Dispose()
# ICONDIR, one ICONDIRENTRY per size (0 = 256), then the PNG data.
$out = New-Object IO.MemoryStream
$w = New-Object IO.BinaryWriter $out
$w.Write([UInt16]0); $w.Write([UInt16]1); $w.Write([UInt16]$frames.Count)
$offset = 6 + 16 * $frames.Count
foreach ($f in $frames) {
    $s = if ($f[0] -ge 256) { 0 } else { $f[0] }
    $w.Write([Byte]$s); $w.Write([Byte]$s); $w.Write([Byte]0); $w.Write([Byte]0)
    $w.Write([UInt16]1); $w.Write([UInt16]32)
    $w.Write([UInt32]$f[1].Length); $w.Write([UInt32]$offset)
    $offset += $f[1].Length
}
foreach ($f in $frames) { $w.Write([byte[]]$f[1]) }
$w.Flush()
[IO.File]::WriteAllBytes($Ico, $out.ToArray())
if ($Rc) {
    $path = (Resolve-Path $Ico).Path.Replace("\", "/")
    Set-Content -Path $Rc -Value "// Generated by tools/make_icon.ps1 (personal builds only).`r`n1 ICON `"$path`"" -Encoding ascii
}
Write-Output "icon: $Ico ($($frames.Count) sizes)"
